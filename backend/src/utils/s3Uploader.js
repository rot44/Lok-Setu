import { S3Client, PutObjectCommand, GetObjectCommand } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";

// Initialize the S3 client using environment credentials
const s3 = new S3Client({
    region: process.env.AWS_REGION,
    credentials: {
        accessKeyId: process.env.AWS_ACCESS_KEY_ID,
        secretAccessKey: process.env.AWS_SECRET_ACCESS_KEY,
    },
});

/**
 * Core upload function — handles any file type
 * @param {Buffer} fileBuffer - Binary file buffer from multer (memoryStorage)
 * @param {string} s3Key - Destination path inside S3 bucket (e.g. "audio/explainers/123-hi.wav")
 * @param {string} contentType - MIME type (e.g. "audio/wav", "application/pdf", "image/jpeg")
 * @returns {Promise<{ s3Key: string, publicUrl: string }>}
 */
export const uploadFileToS3 = async (fileBuffer, s3Key, contentType) => {
    const command = new PutObjectCommand({
        Bucket: process.env.AWS_S3_BUCKET_NAME,
        Key: s3Key,
        Body: fileBuffer,
        ContentType: contentType,
    });

    await s3.send(command);

    const publicUrl = `https://${process.env.AWS_S3_BUCKET_NAME}.s3.${process.env.AWS_REGION}.amazonaws.com/${s3Key}`;
    return { s3Key, publicUrl };
};

/**
 * Upload a TTS Voice Explainer Audio WAV (generated by Gemini 3.8 Flash TTS)
 * Used when a user clicks Play on any scheme card
 */
export const uploadAudioToS3 = async (audioBuffer, explainerId, languageCode) => {
    const s3Key = `audio/explainers/${explainerId}-${languageCode}.wav`;
    return await uploadFileToS3(audioBuffer, s3Key, "audio/wav");
};

/**
 * Upload an official Government Gazette / Policy PDF (uploaded by Admin/Official)
 * Used in the Document ingestion pipeline
 */
export const uploadDocumentPdfToS3 = async (pdfBuffer, documentId) => {
    const s3Key = `documents/official/${documentId}.pdf`;
    return await uploadFileToS3(pdfBuffer, s3Key, "application/pdf");
};

/**
 * Upload a citizen-submitted file from Card 3 (Analyze Documents)
 * Supports: PDF, DOCX, and image photos of printed notices
 * @param {Buffer} fileBuffer - Buffer from multer memoryStorage
 * @param {string} userId - To organise uploads per citizen in S3
 * @param {string} originalFileName - Original file name (e.g. "challan.jpg")
 * @param {string} mimeType - MIME type detected by multer (e.g. "image/jpeg")
 */
export const uploadUserNoticeToS3 = async (fileBuffer, userId, originalFileName, mimeType) => {
    const timestamp = Date.now();
    // Sanitize filename: remove spaces and special chars
    const cleanFileName = originalFileName.replace(/[^a-zA-Z0-9._-]/g, "_");
    const s3Key = `user-uploads/${userId}/${timestamp}-${cleanFileName}`;
    return await uploadFileToS3(fileBuffer, s3Key, mimeType);
};

/**
 * Generate a temporary presigned download URL for private/sensitive documents
 * Default expiry: 24 hours (86400 seconds)
 */
export const getPresignedDownloadUrl = async (s3Key, expiresInSeconds = 86400) => {
    const command = new GetObjectCommand({
        Bucket: process.env.AWS_S3_BUCKET_NAME,
        Key: s3Key,
    });
    return await getSignedUrl(s3, command, { expiresIn: expiresInSeconds });
};

