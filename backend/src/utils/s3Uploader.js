import { S3Client, PutObjectCommand, GetObjectCommand } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { config, isStorageConfigured } from "../config/env.js";
import { ApiError } from "./apiError.js";

// Initialize S3 client instance lazily or safely
let s3ClientInstance = null;

const getS3Client = () => {
    if (!isStorageConfigured()) {
        throw new ApiError(
            503,
            "AWS S3 storage is not configured. Please set AWS_S3_BUCKET_NAME, AWS_ACCESS_KEY_ID, and AWS_SECRET_ACCESS_KEY."
        );
    }

    if (!s3ClientInstance) {
        s3ClientInstance = new S3Client({
            region: config.storage.region,
            credentials: {
                accessKeyId: config.storage.accessKeyId,
                secretAccessKey: config.storage.secretAccessKey,
            },
        });
    }

    return s3ClientInstance;
};

/**
 * Core upload function — handles any file buffer
 * @param {Buffer} fileBuffer - Binary file buffer from multer (memoryStorage)
 * @param {string} s3Key - Destination path inside S3 bucket (e.g. "audio/explainers/123-hi.wav")
 * @param {string} contentType - MIME type (e.g. "audio/wav", "application/pdf", "image/jpeg")
 * @returns {Promise<{ s3Key: string, publicUrl: string }>}
 */
export const uploadFileToS3 = async (fileBuffer, s3Key, contentType) => {
    const s3 = getS3Client();

    try {
        const command = new PutObjectCommand({
            Bucket: config.storage.bucketName,
            Key: s3Key,
            Body: fileBuffer,
            ContentType: contentType,
        });

        await s3.send(command);

        const publicUrl = `https://${config.storage.bucketName}.s3.${config.storage.region}.amazonaws.com/${s3Key}`;
        return { s3Key, publicUrl };
    } catch (error) {
        if (error instanceof ApiError) throw error;
        throw new ApiError(500, `Failed to upload file to S3: ${error.message}`);
    }
};

/**
 * Upload a TTS Voice Explainer Audio WAV (generated by Sarvam Bulbul TTS)
 * Used when a user clicks Play on any scheme card or detail view
 */
export const uploadAudioToS3 = async (audioBuffer, explainerId, languageCode) => {
    const s3Key = `audio/explainers/${explainerId}-${languageCode}.wav`;
    return await uploadFileToS3(audioBuffer, s3Key, "audio/wav");
};

/**
 * Upload an audio explanation WAV for a citizen-uploaded notice
 * Saved in private user-uploads path
 */
export const uploadUserNoticeAudioToS3 = async (audioBuffer, userId, documentId, languageCode) => {
    const s3Key = `user-uploads/${userId}/audio/${documentId}-${languageCode}.wav`;
    return await uploadFileToS3(audioBuffer, s3Key, "audio/wav");
};

/**
 * Upload an official Government Gazette / Policy PDF (uploaded by Admin/Official)
 * Used in the Document ingestion pipeline
 */
export const uploadDocumentPdfToS3 = async (pdfBuffer, documentId) => {
    const s3Key = `documents/official/${documentId}.pdf`;
    return await uploadFileToS3(pdfBuffer, s3Key, "application/pdf");
};

/**
 * Upload a citizen-submitted file from Card 3 (Analyze Documents)
 * Supports: PDF, DOCX, and image photos of printed notices
 * @param {Buffer} fileBuffer - Buffer from multer memoryStorage
 * @param {string} userId - To organise uploads per citizen in S3
 * @param {string} originalFileName - Original file name (e.g. "challan.jpg")
 * @param {string} mimeType - MIME type detected by multer (e.g. "image/jpeg")
 */
export const uploadUserNoticeToS3 = async (fileBuffer, userId, originalFileName, mimeType) => {
    const timestamp = Date.now();
    // Sanitize filename: remove spaces and special chars
    const cleanFileName = originalFileName.replace(/[^a-zA-Z0-9._-]/g, "_");
    const s3Key = `user-uploads/${userId}/${timestamp}-${cleanFileName}`;
    return await uploadFileToS3(fileBuffer, s3Key, mimeType);
};

/**
 * Generate a temporary presigned download URL for private/sensitive documents
 * Default expiry: 24 hours (86400 seconds)
 */
export const getPresignedDownloadUrl = async (s3Key, expiresInSeconds = 86400) => {
    const s3 = getS3Client();

    try {
        const command = new GetObjectCommand({
            Bucket: config.storage.bucketName,
            Key: s3Key,
        });
        return await getSignedUrl(s3, command, { expiresIn: expiresInSeconds });
    } catch (error) {
        if (error instanceof ApiError) throw error;
        throw new ApiError(500, `Failed to generate presigned download URL: ${error.message}`);
    }
};

/**
 * Download a file buffer directly from Amazon S3
 * @param {string} s3Key - Destination path inside S3 bucket
 * @returns {Promise<Buffer>}
 */
export const downloadFileBufferFromS3 = async (s3Key) => {
    if (!s3Key || typeof s3Key !== "string") {
        throw new ApiError(400, "Valid S3 key is required to download document.");
    }

    const s3 = getS3Client();

    try {
        const command = new GetObjectCommand({
            Bucket: config.storage.bucketName,
            Key: s3Key,
        });

        const response = await s3.send(command);
        if (!response.Body) {
            throw new ApiError(404, "S3 object is empty or could not be retrieved.");
        }

        if (typeof response.Body.transformToByteArray === "function") {
            const bytes = await response.Body.transformToByteArray();
            return Buffer.from(bytes);
        }

        return await new Promise((resolve, reject) => {
            const chunks = [];
            response.Body.on("data", (chunk) => chunks.push(chunk));
            response.Body.on("error", reject);
            response.Body.on("end", () => resolve(Buffer.concat(chunks)));
        });
    } catch (error) {
        if (error instanceof ApiError) throw error;
        throw new ApiError(500, `Failed to download file from S3: ${error.message}`);
    }
};

