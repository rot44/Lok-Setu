import mongoose from "mongoose";

const explainerSchema = new mongoose.Schema(
  {
    documentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "Document",
      required: true,
      index: true,
    },
    languageCode: {
      type: String,
      required: true,
      trim: true, // e.g. "hi", "mr", "ta", "bn", "en"
    },
    languageName: {
      type: String,
      trim: true, // e.g. "Hindi", "Marathi", "Tamil"
    },

    // 1. Plain-Language Explanation (Zero legalese)
    plainSummary: {
      type: String,
      required: [true, "Plain summary is required"],
    },

    // 2. Exact Citizen Rights & Protections
    keyRights: [
      {
        type: String,
        trim: true,
      },
    ],

    // 3. Eligibility Matrix Breakdown
    eligibilityCriteria: [
      {
        type: String,
        trim: true,
      },
    ],

    // 4. Real-World Impacts
    citizenImpact: [
      {
        type: String,
        trim: true,
      },
    ],
    businessImpact: [
      {
        type: String,
        trim: true, // Specific compliance, tax rebates, or penalties for MSMEs / shopkeepers
      },
    ],

    // 5. Actionable Roadmap
    requiredDocuments: [
      {
        type: String,
        trim: true,
      },
    ],
    howToApplySteps: [
      {
        type: String,
        trim: true,
      },
    ],

    // 6. Voice Explainer Audio (Generated by Gemini 3.8 Flash TTS & saved to Amazon S3)
    audio: {
      audioUrl: {
        type: String, // Amazon S3 / CDN streaming URL
      },
      s3Key: {
        type: String, // Object key in S3 bucket
      },
      mimeType: {
        type: String,
        default: "audio/wav",
      },
      voiceName: {
        type: String, // e.g., "aoede", "puck"
      },
      durationSeconds: {
        type: Number,
      },
    },

    generatedByModel: {
      type: String,
      default: "gemini-3.8-flash",
    },
  },
  { timestamps: true }
);

// Cache Guarantee: Exactly 1 explainer per language per document
explainerSchema.index({ documentId: 1, languageCode: 1 }, { unique: true });

export const Explainer = mongoose.model("Explainer", explainerSchema);

